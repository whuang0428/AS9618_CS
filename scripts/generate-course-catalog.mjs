import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { unitForLesson } from "./course-structure.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function decodeHtml(value) {
  return value
    .replace(/<[^>]+>/g, "")
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'")
    .replace(/\s+/g, " ")
    .trim();
}

const lessons = Array.from({ length: 150 }, (_, index) => {
  const number = index + 1;
  const id = String(number).padStart(3, "0");
  const html = fs.readFileSync(path.join(root, "web", `lesson-${id}`, "index.html"), "utf8");
  const title = html.match(/<h1>([\s\S]*?)<\/h1>/)?.[1];
  const unit = unitForLesson(number);

  if (!title) throw new Error(`Lesson ${id}: missing h1 title`);
  if (!unit) throw new Error(`Lesson ${id}: missing course unit`);

  return {
    number,
    id,
    title: decodeHtml(title),
    paper: unit.paper,
    section: unit.section,
    unitId: unit.id,
    unitTitle: unit.title,
  };
});

const output = `/* Generated by scripts/generate-course-catalog.mjs. Do not edit by hand. */\n` +
  `(function () {\n  "use strict";\n  const lessons = ${JSON.stringify(lessons, null, 2)};\n` +
  `  for (const lesson of lessons) Object.freeze(lesson);\n` +
  `  globalThis.AS9618CourseCatalog = Object.freeze(lessons);\n}());\n`;

fs.writeFileSync(path.join(root, "web", "course-catalog.js"), output);
console.log(`Generated static course catalog for ${lessons.length} lessons.`);
